//! Interface language for Serika Code.
//!
//! Source strings are English. Every other locale is a dictionary lookup.
//! Missing entries fall back to English, which is also the default locale.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Locale {
    En,
    Es,
    Fr,
    De,
    PtBr,
    It,
    Nl,
    Pl,
    Ru,
    Tr,
    Ja,
    Ko,
    ZhCn,
}

impl Locale {
    pub const ALL: [Locale; 13] = [
        Locale::En,
        Locale::Es,
        Locale::Fr,
        Locale::De,
        Locale::PtBr,
        Locale::It,
        Locale::Nl,
        Locale::Pl,
        Locale::Ru,
        Locale::Tr,
        Locale::Ja,
        Locale::Ko,
        Locale::ZhCn,
    ];

    pub fn code(self) -> &'static str {
        match self {
            Locale::En => "en",
            Locale::Es => "es",
            Locale::Fr => "fr",
            Locale::De => "de",
            Locale::PtBr => "pt-BR",
            Locale::It => "it",
            Locale::Nl => "nl",
            Locale::Pl => "pl",
            Locale::Ru => "ru",
            Locale::Tr => "tr",
            Locale::Ja => "ja",
            Locale::Ko => "ko",
            Locale::ZhCn => "zh-CN",
        }
    }

    /// Name shown in the language menu, in that language.
    pub fn native_name(self) -> &'static str {
        match self {
            Locale::En => "English",
            Locale::Es => "Español",
            Locale::Fr => "Français",
            Locale::De => "Deutsch",
            Locale::PtBr => "Português (Brasil)",
            Locale::It => "Italiano",
            Locale::Nl => "Nederlands",
            Locale::Pl => "Polski",
            Locale::Ru => "Русский",
            Locale::Tr => "Türkçe",
            Locale::Ja => "日本語",
            Locale::Ko => "한국어",
            Locale::ZhCn => "简体中文",
        }
    }

    pub fn parse(value: &str) -> Self {
        let value = value.trim().replace('_', "-");
        for locale in Self::ALL {
            if locale.code().eq_ignore_ascii_case(&value) {
                return locale;
            }
        }
        let base = value.split('-').next().unwrap_or("").to_ascii_lowercase();
        match base.as_str() {
            "en" => Locale::En,
            "es" => Locale::Es,
            "fr" => Locale::Fr,
            "de" => Locale::De,
            "pt" => Locale::PtBr,
            "it" => Locale::It,
            "nl" => Locale::Nl,
            "pl" => Locale::Pl,
            "ru" => Locale::Ru,
            "tr" => Locale::Tr,
            "ja" => Locale::Ja,
            "ko" => Locale::Ko,
            "zh" => Locale::ZhCn,
            _ => Locale::En,
        }
    }
}

