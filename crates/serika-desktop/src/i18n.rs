fn tr<'a>(locale: Locale, en: &'a str, rows: &[(Locale, &'a str)]) -> &'a str {
    rows.iter()
        .find(|(item, _)| *item == locale)
        .map(|(_, text)| *text)
        .filter(|text| !text.is_empty())
        .unwrap_or(en)
}

pub fn fill(template: &str, pairs: &[(&str, &str)]) -> String {
    let mut out = template.to_string();
    for (token, value) in pairs {
        out = out.replace(token, value);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn english_is_the_canonical_default() {
        assert_eq!(Locale::parse("").code(), "en");
        assert_eq!(Locale::parse("zz").code(), "en");
        assert_eq!(t(Locale::En, Key::NewChat), "New chat");
        assert_eq!(t(Locale::En, Key::Library), "Library");
        assert_eq!(t(Locale::En, Key::MessageSerika), "Message Serika");
        assert_eq!(t(Locale::En, Key::Search), "Search");
        assert_eq!(t(Locale::En, Key::Research), "Research");
        assert_eq!(t(Locale::En, Key::Image), "Image");
        assert!(t(Locale::En, Key::Disclaimer).starts_with("Serika can make mistakes"));
    }

    #[test]
    fn dutch_matches_the_previous_ui_copy() {
        assert_eq!(Locale::parse("nl"), Locale::Nl);
        assert_eq!(t(Locale::Nl, Key::NewChat), "Nieuwe chat");
        assert_eq!(t(Locale::Nl, Key::Library), "Bibliotheek");
        assert_eq!(t(Locale::Nl, Key::SearchChats), "Chats zoeken");
        assert_eq!(t(Locale::Nl, Key::Terms), "Voorwaarden");
        assert_eq!(t(Locale::Nl, Key::MessageSerika), "Bericht naar Serika");
        assert_eq!(t(Locale::Nl, Key::Search), "Zoeken");
        assert_eq!(t(Locale::Nl, Key::Research), "Onderzoek");
        assert_eq!(t(Locale::Nl, Key::Image), "Afbeelding");
    }

    #[test]
    fn other_locales_do_not_fall_through_to_dutch() {
        assert_eq!(t(Locale::Ja, Key::NewChat), "新しいチャット");
        assert_eq!(t(Locale::ZhCn, Key::Library), "资料库");
        assert_eq!(t(Locale::Es, Key::SearchModels), "Buscar modelos");
        assert_eq!(t(Locale::Fr, Key::Settings), "Réglages");
        assert_eq!(t(Locale::De, Key::SignOut), "Abmelden");
        assert_eq!(
            fill(t(Locale::En, Key::GoodMorning), &[("{name}", "Noa")]),
            "Good morning, Noa"
        );
    }
}
